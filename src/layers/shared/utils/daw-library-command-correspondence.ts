import { AudioCommandType } from '../types/audioCommand.schema';
import { AudioRuntimeFeature, type AudioRuntimeFeatureStatus } from './audio-runtime-capabilities';

export type DawLibraryCommandCorrespondenceStatus = AudioRuntimeFeatureStatus;

export interface DawLibraryCommandCorrespondence {
  readonly feature?: AudioRuntimeFeature;
  readonly productCommands: readonly AudioCommandType[];
  readonly status: DawLibraryCommandCorrespondenceStatus;
}

const C = AudioCommandType;
const F = AudioRuntimeFeature;

function available(
  feature: AudioRuntimeFeature,
  productCommands: readonly AudioCommandType[] = []
): DawLibraryCommandCorrespondence {
  return { feature, productCommands, status: 'available' };
}

function unsupported(feature: AudioRuntimeFeature): DawLibraryCommandCorrespondence {
  return { feature, productCommands: [], status: 'unsupported' };
}

function internal(): DawLibraryCommandCorrespondence {
  return { productCommands: [], status: 'internal' };
}

